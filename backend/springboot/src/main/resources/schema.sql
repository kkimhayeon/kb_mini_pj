    currency VARCHAR(3),
    expected_at VARCHAR(128),
    expected_at_precision VARCHAR(20),
    source VARCHAR(255),
    evidence_level VARCHAR(32) NOT NULL,
    source_reference TEXT,
    valid_until DATE,
    review_due_at DATE,
    validity_status VARCHAR(32) NOT NULL,
    recorded_at TIMESTAMPTZ,
